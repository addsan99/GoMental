import {mkdir, readFile, writeFile} from 'node:fs/promises'
import {dirname, join} from 'node:path'
import {fileURLToPath} from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const catalog = JSON.parse(await readFile(join(root, 'src/themes/vscode-catalog.json'), 'utf8'))
const defaults = {
  '--bg': '#0e0e12', '--surface': '#16161c', '--surface-2': '#1e1e26', '--surface-3': '#26262f',
  '--text': '#eceaf2', '--text-2': '#cfc9dd', '--text-3': '#a3a0ad', '--border': '#30303a',
  '--border-strong': '#4a4a56', '--accent': '#8b83ff', '--accent-text': '#b9b4ff',
  '--accent-soft': 'rgba(139, 131, 255, .14)', '--accent-soft-line': 'rgba(139, 131, 255, .4)',
}

function parseJSONC(source) {
  let output = ''; let quoted = false
  for (let index = 0; index < source.length; index += 1) {
    const char = source[index]
    if (char === '"' && source[index - 1] !== '\\') quoted = !quoted
    if (!quoted && char === '/' && source[index + 1] === '/') { while (index < source.length && source[index] !== '\n') index += 1; output += '\n'; continue }
    if (!quoted && char === '/' && source[index + 1] === '*') { index += 2; while (index < source.length && !(source[index] === '*' && source[index + 1] === '/')) index += 1; index += 1; continue }
    output += char
  }
  return JSON.parse(output.replace(/,\s*([}\]])/g, '$1'))
}

function category(uiTheme) { return uiTheme === 'vs' ? 'light' : uiTheme === 'hc-light' || uiTheme === 'hc-black' ? 'high-contrast' : 'dark' }
function variables(colors = {}) {
  const pick = (...keys) => keys.map((key) => colors[key]).find(Boolean)
  const background = pick('editor.background', 'sideBar.background', 'workbench.background') || defaults['--bg']
  return {...defaults,
    '--bg': background, '--surface': pick('editorWidget.background', 'editor.background') || background,
    '--surface-2': pick('sideBar.background', 'panel.background', 'editor.background') || background,
    '--surface-3': pick('activityBar.background', 'titleBar.activeBackground', 'sideBar.background') || background,
    '--text': pick('editor.foreground', 'foreground') || defaults['--text'], '--text-2': pick('descriptionForeground', 'editor.foreground', 'foreground') || defaults['--text-2'],
    '--text-3': pick('disabledForeground', 'descriptionForeground') || defaults['--text-3'], '--border': pick('panel.border', 'sideBar.border', 'editorWidget.border') || defaults['--border'],
    '--border-strong': pick('focusBorder', 'contrastBorder', 'editorWidget.border') || defaults['--border-strong'], '--accent': pick('focusBorder', 'textLink.foreground', 'button.background') || defaults['--accent'],
    '--accent-text': pick('textLink.foreground', 'button.foreground', 'editor.foreground') || defaults['--accent-text'], '--accent-soft': pick('editor.selectionBackground', 'list.activeSelectionBackground') || defaults['--accent-soft'],
    '--accent-soft-line': pick('focusBorder', 'list.activeSelectionBackground') || defaults['--accent-soft-line'],
  }
}

const themes = []
for (const {label, category: uiTheme, file} of catalog) {
  try {
    const source = await readFile(join(root, 'src/themes/vscode', file), 'utf8')
    themes.push({id: `vscode-${file.replace(/-theme\.json$/, '').replace(/-color-theme\.json$/, '')}`, label, category: category(uiTheme), variables: variables(parseJSONC(source).colors)})
  } catch (error) {
    console.warn(`Skipping invalid theme source ${file}: ${error.message}`)
  }
}
const output = `// Generated by scripts/generate-vscode-themes.mjs. Do not edit.\nexport const generatedVSCodeThemes = ${JSON.stringify(themes)} as const\nexport const generatedVSCodeThemeOptions = generatedVSCodeThemes.map(({id, label, category}) => ({id, label, category}))\n`
await mkdir(join(root, 'src/themes'), {recursive: true})
await writeFile(join(root, 'src/themes/generated-vscode-themes.ts'), output)
